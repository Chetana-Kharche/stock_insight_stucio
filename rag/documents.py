"""Convert stored data into retrieval-friendly markdown documents (one set per company).

Numbers are written as self-contained "fact blocks" (company + section + metric + unit in the
heading) so that every chunk the RAG engine retrieves carries its own context.
"""
from __future__ import annotations

from typing import Optional

from scraper.parser import FIN_SECTIONS

UNIT = {"INR_CRORE": "₹ crore", "PERCENT": "%", "INR": "₹", "DAYS": "days", "COUNT": "count", "RATIO": "x"}


def _md_table(columns: list[str], rows: list[list[str]]) -> str:
    if not columns:
        return ""
    out = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for r in rows:
        out.append("| " + " | ".join(str(x).replace("|", "/") for x in r) + " |")
    return "\n".join(out)


def profile_doc(payload: dict) -> str:
    m = payload.get("meta", {})
    name = m.get("name", "")
    lines = [
        f"# {name} — company profile",
        f"- NSE symbol: {m.get('nse_symbol') or '-'}; BSE code: {m.get('bse_code') or '-'}",
        f"- Classification: {' > '.join(x for x in [m.get('broad_sector'), m.get('sector'), m.get('broad_industry'), m.get('industry')] if x)}",
        f"- Website: {m.get('website') or '-'}",
        f"- Financial statements basis: {m.get('basis')}; data captured {m.get('captured_at')} from {m.get('source_url')}",
        f"- Latest reported quarter: {m.get('latest_period')}; upcoming result date: {m.get('upcoming_result_date') or '-'}",
        f"- Part of indices: {', '.join(m.get('indices') or []) or '-'}",
        "",
        f"## About {name}",
        payload.get("about") or "-",
        "",
        f"## {name} — summary ratios (as on {str(m.get('captured_at'))[:10]})",
    ]
    for r in payload.get("summary_ratios", []):
        lines.append(f"- {name} {r['name']}: {r['value_text']}")
    if payload.get("pros"):
        lines += ["", f"## {name} — pros (machine generated by Screener)"] + [f"- {x}" for x in payload["pros"]]
    if payload.get("cons"):
        lines += ["", f"## {name} — cons (machine generated by Screener)"] + [f"- {x}" for x in payload["cons"]]
    peers = payload.get("peers") or {}
    if peers.get("rows"):
        cols = peers["columns"][2:]
        rows = [[p["name"]] + [p["values"].get(c, "") for c in cols] for p in peers["rows"]]
        if peers.get("median"):
            rows.append([peers["median"]["name"]] + [peers["median"]["values"].get(c, "") for c in cols])
        lines += ["", f"## {name} — peer comparison ({m.get('industry') or ''})", _md_table(["Company"] + cols, rows)]
    return "\n".join(lines)


def financials_doc(payload: dict) -> str:
    m = payload.get("meta", {})
    name = m.get("name", "")
    lines = [f"# {name} — financial statements ({m.get('basis')}, figures from Screener.in)", ""]

    def block(section_title: str, sec: dict, row: dict, label: Optional[str] = None, values=None):
        metric = label or row["metric"]
        vals = values if values is not None else row["values"]
        is_pct = "%" in metric or any(str(v).endswith("%") for v in vals if v)
        unit = "%" if is_pct else UNIT.get(row.get("unit"), "")
        pairs = [f"{c['label']}: {v}" for c, v in zip(sec["columns"], vals) if v not in ("", None)]
        if not pairs:
            return
        lines.append(f"### {name} — {section_title} — {metric} ({unit})")
        lines.append("; ".join(pairs))
        lines.append("")

    for sid in FIN_SECTIONS:  # fixed order (jsonb does not keep key order)
        sec = payload.get("sections", {}).get(sid)
        if not sec:
            continue
        title = sec.get("title", sid)
        lines.append(f"## {name} — {title}")
        lines.append(sec.get("note", ""))
        lines.append("")
        for row in sec["rows"]:
            block(title, sec, row)
            for sub, vals in (row.get("schedules") or {}).items():
                block(title, sec, row, label=f"{row['metric']} breakdown: {sub}", values=vals["values"])
    if payload.get("growth"):
        lines.append(f"## {name} — compounded growth and returns (from Screener)")
        for g in payload["growth"]:
            lines.append(f"### {name} — {g['title']}")
            lines.append("; ".join(f"{it['period']}: {it['value_text']}" for it in g["rows"]))
            lines.append("")
    shp = payload.get("shareholding") or {}
    for key in ("quarterly", "yearly"):
        sec = shp.get(key)
        if sec:
            lines.append(f"## {name} — shareholding pattern ({key}, % of shares)")
            for row in sec["rows"]:
                block(f"Shareholding {key}", sec, row)
    prices = payload.get("price_history") or []
    if prices:
        monthly = {}
        for p in prices:
            monthly[str(p["date"])[:7]] = p
        lines.append(f"## {name} — share price history (month-end close on NSE, ₹)")
        lines.append("; ".join(f"{k}: {v.get('close')}" for k, v in monthly.items()))
        last = prices[-1]
        lines.append(f"Latest close {last.get('close')} on {last.get('date')}; 50-DMA {last.get('dma50')}; "
                     f"200-DMA {last.get('dma200')}.")
    return "\n".join(lines)


def documents_doc(payload: dict) -> str:
    m = payload.get("meta", {})
    name = m.get("name", "")
    docs = payload.get("documents") or {}
    lines = [f"# {name} — exchange announcements and documents", ""]
    if docs.get("announcements"):
        lines.append(f"## {name} — recent stock exchange announcements")
        for a in docs["announcements"]:
            lines.append(f"- {str(a.get('date') or '')[:10]}: {a['title']}. {a.get('summary') or ''} ({a['url']})")
    if docs.get("annual_reports"):
        lines.append(f"\n## {name} — annual reports")
        lines += [f"- {a['title']}: {a['url']}" for a in docs["annual_reports"]]
    if docs.get("credit_ratings"):
        lines.append(f"\n## {name} — credit rating updates")
        lines += [f"- {a['title']} ({a.get('meta', '')}): {a['url']}" for a in docs["credit_ratings"]]
    if docs.get("concalls"):
        lines.append(f"\n## {name} — earnings call material")
        lines += [f"- {c['period']}: " + ", ".join(f"{k} {u}" for k, u in c["links"].items()) for c in docs["concalls"]]
    return "\n".join(lines)


def news_doc(company_name: str, news: list[dict]) -> str:
    lines = [f"# {company_name} — latest news headlines", ""]
    for n in news:
        lines.append(f"- {str(n.get('published_at') or '')[:10]} — {n['title']} ({n.get('source') or ''}) {n['url']}")
    return "\n".join(lines)


def report_doc(report: dict) -> str:
    c = report.get("company", {})
    name = c.get("name", "")
    lines = [
        f"# {name} — AI-assisted analysis report ({str(report.get('generated_at'))[:10]})",
        f"Stance: {report.get('stance')} | Score: {report.get('score')}/100 | Narrative model: {report.get('model')}",
        "",
        f"## Headline\n{report.get('headline')}",
        f"\n## Executive summary\n{report.get('executive_summary')}",
    ]
    if report.get("investment_thesis"):
        lines += ["\n## Investment thesis"] + [f"- {x}" for x in report["investment_thesis"]]
    lines.append("\n## Scorecard")
    for it in report.get("scorecard", []):
        lines.append(f"- {it['name']} ({it['weight']}% weight): {it['score']}/10 — {'; '.join(it['rationale'])}")
    for s in report.get("sections", []):
        lines += [f"\n## {name} — {s.get('heading')}", s.get("body", "")]
    for key, title in (("key_strengths", "Key strengths"), ("key_risks", "Key risks"),
                       ("monitorables", "Monitorables"), ("news_takeaways", "Key insights from the news")):
        if report.get(key):
            lines += [f"\n## {name} — {title}"] + [f"- {x}" for x in report[key]]
    kr = (report.get("tables") or {}).get("key_ratios") or {}
    if kr.get("rows"):
        lines += [f"\n## {name} — key ratios (calculated)",
                  _md_table(["Metric"] + kr["columns"], [[r["metric"]] + r["values"] for r in kr["rows"]])]
    fc = report.get("forecast") or {}
    if fc.get("ok"):
        lines += [f"\n## {name} — future outlook: model projections (statistical estimates, not facts)",
                  f"Method: {fc.get('method')} Overall confidence: {fc.get('confidence')}. {fc.get('caveat')}"]
        for key, title in (("annual", "projection by fiscal year (E = estimate; ₹ crore, EPS in ₹)"),
                           ("quarterly", "projection for the next four quarters (₹ crore)"),
                           ("derived", "what the projection implies"),
                           ("reliability", "reliability of the projection")):
            t = (fc.get("tables") or {}).get(key) or {}
            if t.get("rows"):
                lines += [f"\n### {name} — {title}",
                          _md_table(["Metric"] + t["columns"],
                                    [[r["metric"]] + list(r["values"]) + [""] * (len(t["columns"]) - len(r["values"]))
                                     for r in t["rows"]])]
        lines += [f"- {n}" for n in fc.get("notes", [])]
    sup = report.get("supplementary") or {}
    if sup.get("items") or sup.get("estimates"):
        lines += [f"\n## {name} — additional data from other websites (not from Screener; third-party figures)"]
        for it in sup.get("items", []) + sup.get("estimates", []):
            period = f", {it['period']}" if it.get("period") and it["period"] != "latest" else ""
            lines.append(f"- {it['metric']}: {it['value']}{period} (source: {it['source']}, {it.get('url', '')})")
    lines += ["\n## Disclaimer", report.get("disclaimer", "")]
    return "\n".join(lines)


def context_for_llm(payload: Optional[dict], report: Optional[dict], news: list[dict], max_chars: int = 120_000) -> str:
    """Compact context used by the Gemini fallback chatbot."""
    parts = []
    if payload:
        parts += [profile_doc(payload), financials_doc(payload), documents_doc(payload)]
    if report:
        parts.append(report_doc(report))
    if news and payload:
        parts.append(news_doc(payload["meta"].get("name", ""), news))
    text = "\n\n".join(parts)
    return text[:max_chars]
