"""Profile tab: account details, usage, name and password, system status, sign out."""
from __future__ import annotations

import pandas as pd
import streamlit as st

from core import repository as repo
from core.auth import AuthError, change_password, sign_out
from ui import components as C
from ui import html as H
from ui import status_view


def _fmt(ts) -> str:
    if not ts:
        return "–"
    try:
        return pd.to_datetime(ts).strftime("%d %b %Y, %H:%M")
    except (TypeError, ValueError):
        return str(ts)


def do_sign_out() -> None:
    sign_out()
    for k in list(st.session_state.keys()):
        del st.session_state[k]
    st.rerun()


def render() -> None:
    user = st.session_state.get("user") or {}
    uid = user.get("id")
    prof = repo.get_profile(uid) or {}
    name = prof.get("full_name") or user.get("full_name") or user.get("email", "").split("@")[0]
    initials = "".join(w[0] for w in name.split()[:2]).upper() or "U"
    C.page_header("Profile", "Your account and how you use Stock Insight Studio.")

    with st.container(border=True):
        a, b = st.columns([3, 1], vertical_alignment="center")
        with a:
            st.html(f"""<div class="vr-prof"><div class="vr-avatar">{H.e(initials)}</div><div>
                <div class="n">{H.e(name)}</div><div class="e">{H.e(prof.get('email') or user.get('email'))}</div>
                <div class="e" style="font-size:.82rem">Member since {H.e(_fmt(prof.get('created_at')))} ·
                last sign-in {H.e(_fmt(prof.get('last_login')))}</div></div></div>""")
        with b:
            if st.button("Sign out", use_container_width=True, key="prof_signout"):
                do_sign_out()

    try:
        s = repo.user_stats(uid)
        C.tiles([("Companies fetched", f"{s['companies']:,}", f"{s['fetches']:,} fetch(es)", None),
                 ("Analysis reports", f"{s['reports']:,}", "generated by you", None),
                 ("Notes", f"{s['notes']:,}", "in your notebook", None),
                 ("Watchlist", f"{s['watchlist']:,}", "companies followed", None),
                 ("Holdings", f"{s['holdings']:,}", "in your portfolio", None)])
    except Exception as e:  # noqa: BLE001
        st.warning(f"Usage figures are not available yet. ({e})")

    left, right = st.columns(2, gap="large")
    with left:
        with st.container(border=True):
            C.subheading("Your name")
            with st.form("prof_name", border=False):
                new_name = st.text_input("Full name", value=prof.get("full_name") or "")
                if st.form_submit_button("Save name", type="primary"):
                    repo.update_profile_name(uid, new_name)
                    st.session_state["user"]["full_name"] = new_name.strip() or None
                    st.success("Saved.")
    with right:
        with st.container(border=True):
            C.subheading("Change password", color="green")
            with st.form("prof_pw", clear_on_submit=True, border=False):
                cur = st.text_input("Current password", type="password")
                n1 = st.text_input("New password", type="password", placeholder="At least 8 characters")
                n2 = st.text_input("Repeat new password", type="password")
                if st.form_submit_button("Change password", type="primary"):
                    if len(n1) < 8:
                        st.warning("Use at least 8 characters.")
                    elif n1 != n2:
                        st.warning("The new passwords do not match.")
                    else:
                        try:
                            change_password(prof.get("email") or user.get("email"), cur, n1)
                            st.success("Password changed. Use it next time you sign in.")
                        except AuthError as e:
                            st.error(str(e))

    with st.expander("System status · database, Gemini, RAGFlow, NSE company list"):
        status_view.render(embedded=True)
